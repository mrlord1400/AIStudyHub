    public static int user(String name, String role) throws Exception {
        try (Connection c = Utils.DBUtils.getConnection(); PreparedStatement ps = c.prepareStatement("INSERT INTO users (username, email, role) VALUES (?,?,?)", Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, name);
            ps.setString(2, name + "@x.com");
            ps.setString(3, role);
            ps.executeUpdate();
            try (ResultSet rs = ps.getGeneratedKeys()) {
                rs.next();
                return rs.getInt(1);
            }
        }
    }

    public static long count(String sql, Object... args) throws Exception {
        try (Connection c = Utils.DBUtils.getConnection(); PreparedStatement ps = c.prepareStatement(sql)) {
            for (int i = 0; i < args.length; i++) {
                ps.setObject(i + 1, args[i]);
            }
            try (ResultSet rs = ps.executeQuery()) {
                rs.next();
                return rs.getLong(1);
            }
        }
    }

    public static String str(String sql) throws Exception {
        try (Connection c = Utils.DBUtils.getConnection(); Statement st = c.createStatement(); ResultSet rs = st.executeQuery(sql)) {
            return rs.next() ? rs.getString(1) : null;
        }
    }

    public static void exec(String sql, Object... args) throws Exception {
        try (Connection c = Utils.DBUtils.getConnection(); PreparedStatement ps = c.prepareStatement(sql)) {
            for (int i = 0; i < args.length; i++) {
                ps.setObject(i + 1, args[i]);
            }
            ps.executeUpdate();
        }
    }

    static int fail = 0;

    public static void check(String name, boolean ok) {
        if (!ok) {
            fail++;
        }
        System.out.println((ok ? "PASS  " : "FAIL  ") + name);
    }

    public static void done() {
        System.out.println(fail == 0 ? "ALL PASS" : fail + " FAILED");
        System.exit(fail == 0 ? 0 : 1);
    }
